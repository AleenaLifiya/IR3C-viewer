"""Build the volumes and answer key of the IR3C "real or reconstructed?" viewer site.

Sources (read only): IR3C_Brats_UQ/nifti_human_review/2026-11-25 (10 subjects per dataset,
x2/x4/x8/x16) and its 2026-11-26 supplement (6 more BraTS and knee subjects, x2/x4). All use
the uniform U0 mask: one slice in every R kept, first and last always kept. Each subject
appears once, either as its acquired volume (diagnostic/<case>/ground_truth) or as its IR3C
reconstruction (blinded/<case>/X{R}_reconstruction). x16 (outside the training range) is never
shown reconstructed. BraTS and knee: supplement subjects are shown reconstructed and the
2026-11-25 subjects fill the rest so that half is real, the extra reconstructed ones being x8
cases drawn with a fixed seed. IXI-tiny (83x44x55, low resolution): one real and one
reconstructed example only. Both kinds get identical treatment: 8-bit, windowed at the 99.5th
percentile of the volume itself, same affine and header, neutral file names.

  python scripts/make_volumes.py --datasets IXI
"""
import argparse
import base64
import json
import os

import nibabel as nib
import numpy as np
import pandas as pd

REVIEW = "/home/aleena/xdiffusion/IR3C_Brats_UQ/nifti_human_review"
SRCS = ("2026-11-25", "2026-11-26")
SUPPLEMENT = "2026-11-26"
SITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "site")
PREFIX = {"BraTS": "BRATS", "OAIZIB": "KNEE", "IXI": "IXI"}
LABEL = {"BraTS": "Brain, T2-FLAIR (BraTS 2023 glioma)", "OAIZIB": "Knee, 3D DESS (OAI-ZIB)",
         "IXI": "Brain, T1-weighted (IXI)"}
SEED = 20261126
PAIR_ONLY = {"IXI"}


def to_uint8(path, out):
    img = nib.load(path)
    x = np.asarray(img.dataobj, dtype=np.float32)
    hi = float(np.percentile(x[x > 0], 99.5))
    y = np.clip(np.round(x / hi * 255.0), 0, 255).astype(np.uint8)
    o = nib.Nifti1Image(y, img.affine)
    o.header.set_zooms(img.header.get_zooms()[:3])
    o.header.set_xyzt_units("mm")
    o.header["cal_min"], o.header["cal_max"] = 0, 255
    nib.save(o, out)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--datasets", default="IXI")
    a = a.parse_args()
    key = pd.concat([pd.read_csv(os.path.join(REVIEW, d, "private_case_key.csv")).assign(src=d)
                     for d in SRCS if os.path.exists(os.path.join(REVIEW, d, "private_case_key.csv"))])
    rng = np.random.default_rng(SEED)
    cases = []
    for ds in a.datasets.split(","):
        k = key[key.dataset == ds].sort_values(["src", "case_id"]).reset_index(drop=True)
        fac = k.sparsity_factor.str[1:].astype(int).to_numpy()
        new = (k.src == SUPPLEMENT).to_numpy()
        real = np.zeros(len(k), bool)
        use = np.ones(len(k), bool)
        if ds in PAIR_ONLY:                       # one real, one reconstructed (x2-x8)
            rec_i, real_i = rng.permutation(np.flatnonzero(fac <= 8))[:2]
            use[:] = False
            use[[rec_i, real_i]] = True
            real[real_i] = True
        else:
            real[~new] = True
            n_rec = len(k) // 2 - int(new.sum())
            cand = rng.permutation(np.flatnonzero(~new & (fac == 8)))
            assert 0 <= n_rec <= len(cand), f"{ds}: cannot balance real and reconstructed"
            real[cand[:n_rec]] = False
        assert not (~real & (fac > 8) & use).any(), "x16 must never be shown reconstructed"
        k, real = k[use].reset_index(drop=True), real[use]
        order = rng.permutation(len(k))
        for n, i in enumerate(order, start=1):
            r = k.iloc[i]
            src_dir = os.path.join(REVIEW, r.src)
            vid = f"{PREFIX[ds].lower()}_{n:02d}"
            src = (os.path.join(src_dir, "diagnostic", r.case_id, "ground_truth.nii.gz") if real[i]
                   else os.path.join(src_dir, r.blinded_file))
            to_uint8(src, os.path.join(SITE, "volumes", f"{vid}.nii.gz"))
            cases.append(dict(id=vid, dataset=ds, label=LABEL[ds], real=bool(real[i]),
                              subject=r.subject_id, source=r.src,
                              factor=r.sparsity_factor, kept=int(r.n_kept),
                              slices=int(r.n_slices)))
            print(vid, "real" if real[i] else f"reconstructed {r.sparsity_factor}", flush=True)
    pub = [{q: c[q] for q in ("id", "dataset", "label")} for c in cases]
    ans = base64.b64encode(json.dumps(
        {c["id"]: [int(c["real"]), c["factor"], c["kept"], c["slices"]] for c in cases}
    ).encode()).decode()
    with open(os.path.join(SITE, "cases.js"), "w") as f:
        f.write("// generated by scripts/make_volumes.py\n")
        f.write("window.CASES = " + json.dumps(pub) + ";\n")
        f.write("window.KEY = \"" + ans + "\";\n")
    # private record of the assignment (never published)
    pd.DataFrame(cases).to_csv(os.path.join(SITE, "..", "private_assignment.csv"), index=False)


if __name__ == "__main__":
    main()
